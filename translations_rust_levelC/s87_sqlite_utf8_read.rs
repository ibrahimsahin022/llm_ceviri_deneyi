use std::io::{self, BufRead};

const TRANS1: [u8; 64] = [
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
    0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x00, 0x01, 0x02, 0x03, 0x00, 0x01, 0x00, 0x00,
];

fn sqlite3_utf8_read(bytes: &[u8], pos: &mut usize) -> u32 {
    let mut c = bytes[*pos] as u32;
    *pos += 1;
    if c >= 0xc0 {
        c = TRANS1[(c - 0xc0) as usize] as u32;
        while *pos < bytes.len() && (bytes[*pos] & 0xc0) == 0x80 {
            c = (c << 6) + (0x3f & bytes[*pos]) as u32;
            *pos += 1;
        }
        if c < 0x80 || (c & 0xFFFFF800) == 0xD800 || (c & 0xFFFFFFFE) == 0xFFFE {
            c = 0xFFFD;
        }
    }
    c
}

fn main() {
    let stdin = io::stdin();
    let line = stdin.lock().lines().next().unwrap().unwrap();
    let bytes = line.as_bytes();
    let mut pos = 0usize;
    let mut out = Vec::new();
    while pos < bytes.len() {
        let c = sqlite3_utf8_read(bytes, &mut pos);
        out.push(c.to_string());
    }
    println!("{}", out.join(" "));
}
